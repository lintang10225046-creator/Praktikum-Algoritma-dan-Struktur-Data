# 1. Variabel nilai dan kehadiran
nilai = 82
kehadiran = 90

# 2. Memeriksa masing-masing syarat
syarat_nilai = nilai >= 75
syarat_kehadiran = kehadiran >= 80

print("Nilai memenuhi syarat:", syarat_nilai)
print("Kehadiran memenuhi syarat:", syarat_kehadiran)

# 3. Menggunakan operator AND
print("Lulus dengan AND:", syarat_nilai and syarat_kehadiran)

# 5 Menggunakan operator OR
print("Lulus dengan OR:", syarat_nilai or syarat_kehadiran)



